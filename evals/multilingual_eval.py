"""E8 — Multilingual retrieval: does "translate to English, then search the English index" work?

Arms (dev set only, 50 questions; gold chunk IDs carry over because IDs are language-independent):
  en_orig     original English question, searched as is (the existing baseline)
  en_rewrite  English question through the rewrite step (control: isolates rewrite noise from language)
  <lang>_rewrite   translated question -> rewrite into English with the Act's terms -> English index
  <lang>_direct    translated question embedded as is against the English index (no translation)
Deferred: native search in a per-language index (needs the other language versions of the Act,
which must be saved from a browser; EUR-Lex blocks scripted downloads).

Step 1 (once): translate the dev questions with a STRONGER model than the rewriter, phrased as a native
non-lawyer would ask, and freeze them in evals/retrieval_cases_ml.yaml (never regenerated by `run`).
Step 2: run the arms. The rewrite prompt is experiment-local: the production GUARD_SYSTEM is not changed
until this experiment supports the design. Same guard model and thinking level as production.

usage:
  uv run --env-file .env python -m evals.multilingual_eval translate
  uv run --env-file .env python -m evals.multilingual_eval run [--reuse-rewrites]
"""

from __future__ import annotations

import argparse
import json
import statistics
import sys
from concurrent.futures import ThreadPoolExecutor
from datetime import UTC, date, datetime
from pathlib import Path

import yaml

from app.chat.prompts import GUARD_SCHEMA, GUARD_SYSTEM, guard_user_message
from app.config import Settings
from app.llm.base import Message, make_llm
from app.retrieval.search import Retriever

from .run_retrieval_eval import matches

LANGS = {"lt": "Lithuanian", "pl": "Polish", "fi": "Finnish", "fr": "French"}
DEV = Path("evals/retrieval_cases.yaml")
ML = Path("evals/retrieval_cases_ml.yaml")
OUT = Path("evals/results/multilingual_dev.json")
TRANSLATE_MODEL = "gemini-3.8-flash"  # stronger than the flash-lite rewriter: limits round-trip bias
K = 8

TRANSLATE_SYSTEM = """You translate user questions about the EU AI Act into {lang}, for a test set.
Write each question the way a native {lang} speaker who is NOT a lawyer would type it to a chatbot:
natural, everyday {lang}. Do not keep English words or English legal terms; use the normal {lang} words.
If the question names an article, annex or recital, write that reference the way {lang} speakers do
(native word for "Article", native word order). Keep the meaning exactly; do not add or remove details.
Return JSON: {{"items": [{{"id": ..., "q": ...}}]}} with the same ids, in the same order."""

TRANSLATE_SCHEMA = {
    "type": "object",
    "properties": {"items": {"type": "array", "items": {
        "type": "object", "properties": {"id": {"type": "string"}, "q": {"type": "string"}},
        "required": ["id", "q"]}}},
    "required": ["items"],
}

# Experiment-local guard prompt: production prompt + the planned multilingual addendum.
ML_ADDENDUM = """

MULTILINGUAL INPUT. The user may write in any EU language. Additionally:
- "language": the ISO 639-1 code of the language of the NEW message (e.g. "en", "lt", "pl", "fi", "fr").
- "standalone_question" must ALWAYS be in English, using the English terminology of the AI Act
  (e.g. provider, deployer, high-risk AI system, general-purpose AI model, placing on the market).
  Write references to provisions in English form: "Article 5(1)", "Annex III", "Recital 47"."""
ML_SYSTEM = GUARD_SYSTEM + ML_ADDENDUM
ML_SCHEMA = json.loads(json.dumps(GUARD_SCHEMA))
ML_SCHEMA["properties"]["language"] = {"type": "string"}
ML_SCHEMA["required"].append("language")


# ---------------------------------------------------------------- step 1
def translate() -> None:
    if ML.exists():
        sys.exit(f"{ML} exists and is frozen; delete it deliberately to regenerate.")
    cases = yaml.safe_load(DEV.read_text())
    llm = make_llm(TRANSLATE_MODEL)
    payload = json.dumps([{"id": c["id"], "q": c["q"]} for c in cases], ensure_ascii=False)
    out = {c["id"]: {"id": c["id"], "style": c["style"], "gold": c["gold"], "en": c["q"]} for c in cases}
    cost = 0.0
    for code, name in LANGS.items():
        r = llm.generate(TRANSLATE_SYSTEM.format(lang=name), [Message("user", payload)],
                         max_tokens=12000, thinking="low", json_schema=TRANSLATE_SCHEMA)
        cost += r.usage.cost_usd()
        items = {it["id"]: it["q"] for it in json.loads(r.text)["items"]}
        missing = set(out) - set(items)
        if missing:
            sys.exit(f"{name}: missing translations for {sorted(missing)}")
        for cid in out:
            out[cid][code] = items[cid]
        print(f"{name}: {len(items)} questions")
    header = (f"# E8 multilingual test questions: the dev retrieval questions translated by {TRANSLATE_MODEL}\n"
              f"# on {date.today()}, phrased as native non-lawyers would ask. FROZEN: generated once, not by `run`.\n"
              "# Not yet checked by native speakers: results based on them are provisional.\n"
              "# gold IDs are copied from the English set (chunk IDs are language-independent).\n")
    ML.write_text(header + yaml.safe_dump(list(out.values()), allow_unicode=True, sort_keys=False, width=200))
    print(f"wrote {ML} (translation cost ${cost:.4f})")


# ---------------------------------------------------------------- step 2
def _first_hit(chunks, gold) -> int | None:
    return next((n for n, c in enumerate(chunks, 1) if matches(c, gold)), None)


def _search(r: Retriever, q: str) -> dict:
    hits, top = r.retrieve(q, k=K)
    lists, _ = r._rankings(q, 50, True, False)  # pure; dense list for the dense-only view
    dense = [r.chunks[i] for i in lists.get("dense", [])[:K]]
    return {"product": [h.chunk for h in hits], "dense": dense, "top": top,
            "resolver": bool(r.resolver.resolve_scored(q))}


def _rewrite(llm, s: Settings, q: str) -> dict:
    res = llm.generate(ML_SYSTEM, [Message("user", guard_user_message([], q))], max_tokens=s.guard_max_tokens,
                       thinking=s.guard_thinking, json_schema=ML_SCHEMA)
    g = json.loads(res.text)
    return {"guard": g, "cost": res.usage.cost_usd(), "latency": res.usage.latency_s,
            "in_tokens": res.usage.input_tokens, "out_tokens": res.usage.output_tokens}


def _metrics(rows: list[dict], floor: float) -> dict:
    n = len(rows)
    out = {"n": n}
    for view in ("product", "dense"):
        ranks = [row[f"{view}_rank"] for row in rows]
        out[view] = {"recall@1": round(sum(1 for x in ranks if x and x <= 1) / n, 3),
                     "recall@5": round(sum(1 for x in ranks if x and x <= 5) / n, 3),
                     "mrr": round(sum(1 / x for x in ranks if x) / n, 3)}
    tops = [row["top"] for row in rows if row["top"] is not None]
    out["floor_blocked"] = sum(1 for t in tops if t < floor)
    out["min_top_similarity"] = round(min(tops), 3) if tops else None
    ref = [row for row in rows if row["style"] == "ref"]
    if ref:
        out["ref_recall@5"] = round(sum(1 for row in ref if (row["product_rank"] or 99) <= 5) / len(ref), 3)
        out["ref_resolver_fired"] = f"{sum(1 for row in ref if row['resolver'])}/{len(ref)}"
    if "guard" in rows[0]:
        out["guard"] = {
            "language_correct": f"{sum(1 for row in rows if row['guard'].get('language', '').lower()[:2] == row['lang'])}/{n}",
            "labels": {lab: sum(1 for row in rows if row["guard"].get("label") == lab) for lab in ("in", "out", "ambiguous")},
            "cost_usd_total": round(sum(row["cost"] for row in rows), 5),
            "latency_p50_s": round(statistics.median(row["latency"] for row in rows), 2),
            "latency_max_s": round(max(row["latency"] for row in rows), 2),
            "avg_tokens_in_out": [round(statistics.mean(row["in_tokens"] for row in rows)),
                                  round(statistics.mean(row["out_tokens"] for row in rows))],
        }
    return out


def _stored_rewrites() -> dict:
    """Rewrites from the previous run, so a retrieval-side change can be re-scored without new (non-deterministic)
    guard calls: the before/after difference is then due to the change alone."""
    prev = json.loads(OUT.read_text())["cases"]
    keep = ("guard", "cost", "latency")
    return {(row["lang"], row["id"]): {k: row[k] for k in keep} | {"in_tokens": 0, "out_tokens": 0}
            for arm, rows in prev.items() if arm.endswith("_rewrite") for row in rows}


def run(reuse: bool = False) -> None:
    if not ML.exists():
        sys.exit(f"{ML} missing: run `translate` first")
    cases = [c for c in yaml.safe_load(ML.read_text())]
    s = Settings()
    r = Retriever(embedder="gemini2")
    llm = make_llm(s.guard_model)

    # rewrite calls in parallel (network-bound); retrieval sequential
    jobs = [("en", c) for c in cases] + [(code, c) for code in LANGS for c in cases]
    if reuse:
        rw = _stored_rewrites()
    else:
        with ThreadPoolExecutor(8) as ex:
            rewrites = list(ex.map(lambda j: _rewrite(llm, s, j[1][j[0]]), jobs))
        rw = {(code, c["id"]): w for (code, c), w in zip(jobs, rewrites, strict=True)}

    arms: dict[str, list[dict]] = {}

    def add(arm, lang, c, q, extra=None):
        found = _search(r, q)
        row = {"id": c["id"], "style": c["style"], "lang": lang, "q": q, "gold": c["gold"],
               "product_rank": _first_hit(found["product"], c["gold"]), "dense_rank": _first_hit(found["dense"], c["gold"]),
               "top": found["top"], "resolver": found["resolver"],
               "product_top3": [ch.id for ch in found["product"][:3]]}
        arms.setdefault(arm, []).append(row | (extra or {}))

    for c in cases:
        add("en_orig", "en", c, c["en"])
        w = rw[("en", c["id"])]
        add("en_rewrite", "en", c, w["guard"].get("standalone_question") or c["en"], w | {"original": c["en"]})
        for code in LANGS:
            w = rw[(code, c["id"])]
            add(f"{code}_rewrite", code, c, w["guard"].get("standalone_question") or c[code], w | {"original": c[code]})
            add(f"{code}_direct", code, c, c[code])

    if any(row["top"] is None for rows in arms.values() for row in rows):
        sys.exit("dense retrieval failed for some queries (embedding API): results would be invalid")

    metrics = {arm: _metrics(rows, r.relevance_floor) for arm, rows in arms.items()}
    base = metrics["en_rewrite"]["product"]
    for arm, m in metrics.items():
        m["gap_vs_en_rewrite_pp"] = {k: round((base[k] - m["product"][k]) * 100, 1) for k in ("recall@1", "recall@5", "mrr")}
    res = {
        "experiment": "E8 multilingual retrieval (dev)",
        "run_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "embedder": "gemini2", "relevance_floor": r.relevance_floor, "k": K,
        "guard_model": s.guard_model, "guard_thinking": s.guard_thinking, "translate_model": TRANSLATE_MODEL,
        "cases_file": str(ML), "rewrites_reused": reuse, "metrics": metrics,
        "cases": {arm: [{k: v for k, v in row.items() if k not in ("in_tokens", "out_tokens")} for row in rows]
                  for arm, rows in arms.items()},
    }
    OUT.write_text(json.dumps(res, indent=2, ensure_ascii=False))

    print(f"{'arm':<12} {'P r@1':>6} {'P r@5':>6} {'P MRR':>6} | {'D r@1':>6} {'D r@5':>6} | {'gap r@5':>7} "
          f"{'floor':>5} {'minsim':>6} {'ref r@5':>7} {'lang':>6} labels")
    for arm, m in metrics.items():
        g = m.get("guard", {})
        print(f"{arm:<12} {m['product']['recall@1']:>6} {m['product']['recall@5']:>6} {m['product']['mrr']:>6} | "
              f"{m['dense']['recall@1']:>6} {m['dense']['recall@5']:>6} | {m['gap_vs_en_rewrite_pp']['recall@5']:>7} "
              f"{m['floor_blocked']:>5} {m['min_top_similarity']:>6} {m.get('ref_recall@5', ''):>7} "
              f"{g.get('language_correct', ''):>6} {g.get('labels', '')}")
    gs = [m["guard"] for m in metrics.values() if "guard" in m]
    print(f"guard: total ${sum(x['cost_usd_total'] for x in gs):.4f}, p50 latency per arm "
          f"{[x['latency_p50_s'] for x in gs]}")
    print(f"wrote {OUT}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("step", choices=["translate", "run"])
    ap.add_argument("--reuse-rewrites", action="store_true", help="re-score with the previous run's rewrites")
    args = ap.parse_args()
    translate() if args.step == "translate" else run(args.reuse_rewrites)


if __name__ == "__main__":
    main()
